export const findSareeDetails = (query: string, fallbackOverrides?: Partial<SareeDetail>): SareeDetail => {
  const normalized = query.toLowerCase();
  const found = GRAND_SAREES_COLLECTION.find(
    (s) =>
      s.id.toLowerCase() === normalized ||
      s.name.toLowerCase().includes(normalized) ||
      normalized.includes(s.id.toLowerCase()) ||
      (s.subtitle && s.subtitle.toLowerCase().includes(normalized))
  );
  if (found) {
    return fallbackOverrides ? { ...found, ...fallbackOverrides } : found;
  }
  const base = GRAND_SAREES_COLLECTION[0];
  if (fallbackOverrides) {
    return {
      ...base,
      id: fallbackOverrides.id || `saree-${query.replace(/\s+/g, '-').toLowerCase()}`,
      name: fallbackOverrides.name || query,
      price: fallbackOverrides.price || base.price,
      image: fallbackOverrides.image || base.image,
      ...fallbackOverrides,
    };
  }
  return base;
};
